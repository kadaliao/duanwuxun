// 场景图：最短路线（用于要事箭头指向出口）
export function sceneRoute(from, to) {
  if (from === to) return [];
  const prev = { [from]: null }; const q = [from];
  while (q.length) { const s = q.shift(); for (const e of SCENES[s].exits || []) { if (prev[e.to] !== undefined) continue; prev[e.to] = s; if (e.to === to) { const path = [to]; let c = to; while (prev[c] !== from) { c = prev[c]; path.unshift(c); } return path; } q.push(e.to); } }
  return null;
}
